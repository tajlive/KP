#!/usr/bin/env node
/**
 * 🔥 Error Pattern Promoter - Auto-promoterer FIX-entries fra diary til .knowledge/errors/
 *
 * Kjores automatisk etter hver KIMI-session (via post-task hook) eller manuelt.
 * Parser diary.jsonl etter type: "FIX" eller "AUTO" med status != "GO",
 * sjekker om monstret allerede er dokumentert i .knowledge/errors/,
 * og genererer en ny error-pattern-fil hvis ikke.
 */

import { readFile, writeFile, readdir } from 'fs/promises';
import { existsSync, mkdirSync } from 'fs';
import { join } from 'path';
import { createHash } from 'crypto';

const DIARY_PATH = '.kimi/diary.jsonl';
const ERRORS_DIR = '.knowledge/errors';
const LOOKBACK_DAYS = 30;

function hashTask(task) {
  return createHash('sha256').update(task.toLowerCase().trim()).digest('hex').slice(0, 12);
}

async function loadDiary() {
  if (!existsSync(DIARY_PATH)) return [];
  const content = await readFile(DIARY_PATH, 'utf-8');
  return content
    .split('\n')
    .filter(Boolean)
    .map(line => {
      try { return JSON.parse(line); } catch { return null; }
    })
    .filter(Boolean);
}

async function loadExistingErrors() {
  if (!existsSync(ERRORS_DIR)) return [];
  const files = await readdir(ERRORS_DIR);
  const errors = [];
  for (const f of files.filter(f => f.endsWith('.md'))) {
    const content = await readFile(join(ERRORS_DIR, f), 'utf-8');
    const hashes = [...content.matchAll(/<!-- task-hash: ([a-f0-9]+) -->/g)].map(m => m[1]);
    errors.push({ file: f, hashes });
  }
  return errors;
}

function isAlreadyDocumented(taskHash, existingErrors) {
  return existingErrors.some(e => e.hashes.includes(taskHash));
}

function generateErrorDoc(entry, taskHash) {
  const date = entry.ts ? entry.ts.split('T')[0] : new Date().toISOString().split('T')[0];
  const slug = entry.task
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .slice(0, 50)
    .replace(/^-|-$/g, '');
  const filename = `${date}-${slug}.md`;

  const tags = entry.tags?.length ? entry.tags.join(', ') : 'general';
  const files = entry.files || 'N/A';
  const agent = entry.agent || 'unknown';
  const status = entry.status || 'WIP';
  const rating = entry.rating || 3;

  const content = `# ${entry.task}

<!-- task-hash: ${taskHash} -->
<!-- auto-generated by error-pattern-promoter.mjs -->

**Dato:** ${date}  
**Agent:** ${agent}  
**Status:** ${status}  
**Rating:** ${rating}/5  
**Filer:** ${files}  
**Tags:** ${tags}

## Problem
${entry.task}

## Kontekst
- Type: ${entry.type}
- Tidspunkt: ${entry.ts || 'ukjent'}

## Losning
<!-- TODO: Fyll inn detaljert losning og rotarsak -->
> _Losningen er dokumentert i diary.jsonl. Utfyllende teknisk analyse kreves._

## Forebygging
<!-- TODO: Hvordan unnga dette i fremtiden? -->

## Relatert
- Se ogsa: diary.jsonl (sok etter "${entry.task.slice(0, 30)}")

---
*Auto-generert av error-pattern-promoter. Oppdater manuelt med dypere analyse.*
`;

  return { filename, content };
}

async function main() {
  console.log('🔥 Error Pattern Promoter\n');

  if (!existsSync(ERRORS_DIR)) {
    mkdirSync(ERRORS_DIR, { recursive: true });
  }

  const entries = await loadDiary();
  const existingErrors = await loadExistingErrors();

  const cutoff = new Date();
  cutoff.setDate(cutoff.getDate() - LOOKBACK_DAYS);

  const candidates = entries.filter(e => {
    if (!e.ts) return false;
    const d = new Date(e.ts);
    if (d < cutoff) return false;
    const isFix = e.type === 'FIX';
    const isNonGo = e.status && e.status !== 'GO';
    const isAutoWithProblem = e.type === 'AUTO' && e.rating && e.rating <= 2;
    return isFix || isNonGo || isAutoWithProblem;
  });

  let promoted = 0;
  let skipped = 0;

  for (const entry of candidates) {
    const taskHash = hashTask(entry.task);
    if (isAlreadyDocumented(taskHash, existingErrors)) {
      skipped++;
      continue;
    }

    const { filename, content } = generateErrorDoc(entry, taskHash);
    const filepath = join(ERRORS_DIR, filename);

    if (existsSync(filepath)) {
      skipped++;
      continue;
    }

    await writeFile(filepath, content);
    console.log(`   ✅ Promotert: ${filename}`);
    promoted++;
  }

  console.log(`\n📊 Oppsummering:`);
  console.log(`   Kandidater (siste ${LOOKBACK_DAYS} dager): ${candidates.length}`);
  console.log(`   Promotert: ${promoted}`);
  console.log(`   Skippet (allerede dokumentert): ${skipped}`);

  if (promoted > 0) {
    console.log(`\n🧠  Kjør: hermes memory sync for å indeksere nye error patterns.`);
  }
}

main().catch(err => {
  console.error('❌ Feil:', err.message);
  process.exit(1);
});
