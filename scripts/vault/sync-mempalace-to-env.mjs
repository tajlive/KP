#!/usr/bin/env node
/**
 * ⬇️ Sync secrets from MemPalace KG back to a .env file.
 *
 * Usage:
 *   node scripts/vault/sync-mempalace-to-env.mjs [--env-path <path>] --force [--dry-run]
 *
 * Default env file: .env.local
 *
 * Note: --env-path is used instead of --env-file because Node.js 24 treats
 * --env-file as a native runtime flag.
 *
 * --force is required to overwrite an existing env file.
 */

import { resolve, dirname } from "path";
import { fileURLToPath } from "url";
import { existsSync } from "fs";
import { execFileSync } from "child_process";
import { parseEnvFile, writeEnvFile } from "./lib/env.mjs";
import { decrypt } from "./lib/crypto.mjs";
import { kgFindSubjects, getKGPath } from "./lib/mempalace.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "../..");

function parseArgs(argv) {
  const args = {
    envFile: resolve(ROOT, ".env.local"),
    force: false,
    dryRun: false,
  };

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--env-path" || arg === "-e") {
      args.envFile = resolve(ROOT, argv[++i]);
    } else if (arg === "--force" || arg === "-f") {
      args.force = true;
    } else if (arg === "--dry-run" || arg === "-d") {
      args.dryRun = true;
    }
  }

  return args;
}

const args = parseArgs(process.argv.slice(2));

if (existsSync(args.envFile) && !args.force && !args.dryRun) {
  console.error(
    `Refusing to overwrite existing env file ${args.envFile}. Use --force to overwrite.`
  );
  process.exit(1);
}

let keyHex;
try {
  keyHex = execFileSync(process.execPath, [resolve(__dirname, "vault-key.mjs")], {
    cwd: ROOT,
    encoding: "utf8",
    env: process.env,
  })
    .split("\n")
    .find((line) => /^[0-9a-f]{64}$/i.test(line));
} catch (err) {
  console.error("Failed to load vault key:", err.message);
  process.exit(1);
}

if (!keyHex) {
  console.error("Vault key not found or invalid.");
  process.exit(1);
}

const subjects = kgFindSubjects("secret:");
if (subjects.length === 0) {
  console.error(`No secrets found in ${getKGPath()} matching "secret:".`);
  process.exit(0);
}

const decryptedEntries = [];
const errors = [];

for (const { subject, facts } of subjects) {
  const keyName = subject.slice("secret:".length);
  const encryptedFact = facts.find((f) => f.predicate === "encrypted_value");

  if (!encryptedFact) {
    errors.push({ key: keyName, reason: "missing encrypted_value" });
    continue;
  }

  try {
    const aad = `secret:${keyName}`;
    const value = decrypt(encryptedFact.object, keyHex, aad);
    decryptedEntries.push({ key: keyName, value });
  } catch (err) {
    errors.push({ key: keyName, reason: err.message });
  }
}

if (args.dryRun) {
  console.log(`Dry-run: would write ${decryptedEntries.length} secrets to ${args.envFile}`);
  if (errors.length > 0) {
    console.error(`  ${errors.length} decryption errors:`);
    for (const e of errors) console.error(`    - ${e.key}: ${e.reason}`);
  }
  for (const entry of decryptedEntries) {
    const masked = entry.value.length > 4
      ? `${entry.value.slice(0, 2)}***${entry.value.slice(-2)}`
      : "****";
    console.log(`${entry.key}=${masked}`);
  }
  process.exit(0);
}

// Preserve non-secret lines from the existing env file when overwriting.
let existingEntries = [];
if (existsSync(args.envFile)) {
  existingEntries = parseEnvFile(args.envFile);
}

const preservedEntries = existingEntries.filter((e) => {
  // Drop secrets that are being restored from MemPalace.
  if (e.key && subjects.some((s) => s.subject === `secret:${e.key}`)) {
    return false;
  }
  // Drop stale auto-generated headers from previous runs.
  if (
    e.comment &&
    e.comment.includes("Auto-generated by sync-mempalace-to-env.mjs")
  ) {
    return false;
  }
  return true;
});

// Insert a header comment.
const headerComment = `# Auto-generated by sync-mempalace-to-env.mjs at ${new Date().toISOString()}`;
const newEntries = [
  { comment: headerComment },
  ...preservedEntries,
  ...decryptedEntries,
];

try {
  writeEnvFile(args.envFile, newEntries);
  console.log(
    `✅ Wrote ${decryptedEntries.length} decrypted secrets to ${args.envFile}`
  );
  if (errors.length > 0) {
    console.error(`  ${errors.length} decryption errors (not written):`);
    for (const e of errors) console.error(`    - ${e.key}: ${e.reason}`);
  }
} catch (err) {
  console.error("❌ Failed to write env file:", err.message);
  process.exit(1);
}
