import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
await page.goto('https://www.klarpakke.no/no/login', { waitUntil: 'networkidle', timeout: 90000 });
await page.waitForTimeout(3000);
await page.waitForTimeout(4000);
await page.fill('input[type="email"]', 'tomarnejensen@gmail.com');
await page.locator('input[type="password"]').first().fill('TestTest123!');
await page.waitForTimeout(1500);
await page.click('button[type="submit"]');
await page.waitForTimeout(30000); console.log("ETTER LOGIN:", page.url());
await page.waitForTimeout(4000);
await page.goto('https://www.klarpakke.no/no/dashboard/autopilot', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForTimeout(9000);
await page.screenshot({ path: '/tmp/s9-top.png' });
await page.evaluate(() => window.scrollTo(0, 844));
await page.waitForTimeout(1500);
await page.screenshot({ path: '/tmp/s9-mid.png' });
await page.evaluate(() => window.scrollTo(0, 1688));
await page.waitForTimeout(1500);
await page.screenshot({ path: '/tmp/s9-low.png' });
await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
await page.waitForTimeout(1500);
await page.screenshot({ path: '/tmp/s9-bottom.png' });
console.log('SCROLLHEIGHT:', await page.evaluate(() => document.body.scrollHeight));
await browser.close();
