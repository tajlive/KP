import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0,200)); });
page.on('pageerror', e => errors.push('PAGEERROR: ' + String(e).slice(0,200)));
await page.goto('https://www.klarpakke.no/no/login', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.fill('input[type="email"]', 'tomarnejensen@gmail.com');
await page.fill('input[type="password"]', 'TestTest123!');
await page.click('button[type="submit"]');
await page.waitForTimeout(12000);
console.log('URL:', page.url());
const banner = await page.evaluate(() => document.body.innerText.slice(0, 400));
console.log('BODY:', banner.replace(/\n+/g, ' | '));
console.log('ERRORS:', errors.slice(0,5));
await browser.close();
