import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
await p.goto('https://www.klarpakke.no/no/login');
await p.fill('input[type="email"]', 'tomarnejensen@gmail.com');
await p.fill('input[type="password"]', 'TestTest123!');
await p.click('button[type="submit"]');
await p.waitForTimeout(6000);
await p.goto('https://www.klarpakke.no/no/profile', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(7000);
console.log('URL:', p.url());
await p.screenshot({ path: '/tmp/s13-profil.png' });
await p.evaluate(() => window.scrollTo(0, 99999));
await p.waitForTimeout(1500);
await p.screenshot({ path: '/tmp/s13-profil-bunn.png' });
await b.close();
